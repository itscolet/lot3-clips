export const DICTS: Record<Lang, Dict> = { en, es };
export const dict = (lang: Lang) => DICTS[lang];

/** Translate a raw status / label key, falling back to the key itself. */
export const tStatus = (t: Dict, s: string) => t.status[s] ?? s;
export const tLabel = (t: Dict, s: string) => t.label[s] ?? s;

const LOCALE: Record<Lang, string> = { en: "en-US", es: "es-MX" };

export function timeAgoL(iso: string | null | undefined, lang: Lang) {
  if (!iso) return "—";
  const t = DICTS[lang].time;
  const s = Math.max(1, Math.round((Date.now() - new Date(iso).getTime()) / 1000));
  if (s < 60) return t.s(s);
  const m = Math.round(s / 60);
  if (m < 60) return t.m(m);
  const h = Math.round(m / 60);
  if (h < 24) return t.h(h);
  const d = Math.round(h / 24);
  if (d < 30) return t.d(d);
  return new Date(iso).toLocaleDateString(LOCALE[lang], { month: "short", day: "numeric" });
}

export const shortDateL = (iso: string | null | undefined, lang: Lang) =>
  iso ? new Date(iso).toLocaleDateString(LOCALE[lang], { month: "short", day: "numeric", year: "numeric" }) : "—";

/** Map raw Supabase auth errors to friendly copy. */
export function authError(msg: string, t: Dict) {
  const m = msg.toLowerCase();
  if (m.includes("invalid login credentials")) return t.authErr.wrongCreds;
  if (m.includes("already registered") || m.includes("already been registered")) return t.authErr.exists;
  if (m.includes("password should be") || m.includes("weak password")) return t.authErr.weakPw;
  if (m.includes("email not confirmed")) return t.authErr.notConfirmed;
  if (m.includes("rate limit") || m.includes("too many")) return t.authErr.rate;
  if (m.includes("invalid") && m.includes("email")) return t.authErr.badEmail;
  return msg;
}
